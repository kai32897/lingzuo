import puppeteer from "puppeteer-core";
const b = await puppeteer.launch({ executablePath: "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe", headless: "new", args: ["--no-sandbox", "--disable-http2", "--host-resolver-rules=MAP lingzuo-ai.netlify.app 13.215.239.219"] });
const p = await b.newPage();
await p.setViewport({ width: 1440, height: 1000 });
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
p.on("console", (m) => { if (m.type() === "error") errs.push(m.text()); });
await p.goto("https://lingzuo-ai.netlify.app/", { waitUntil: "domcontentloaded", timeout: 60000 });
await new Promise((r) => setTimeout(r, 4000));
const text = await p.evaluate(() => document.body.textContent ?? "");
console.log("title", await p.title());
console.log("remote", text.includes("真实发布测试"));
console.log("seed", text.includes("便利店夜班"));
console.log("hero", await p.$$eval(".hero-card h2", (n) => n.map((x) => x.textContent?.trim())));
console.log("login", await p.$$eval(".header-login", (n) => n.length));
console.log("overflow", await p.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth));
console.log("errors", errs);
await p.screenshot({ path: ".shots/public-real-home.png" });
await b.close();
