import puppeteer from "puppeteer-core";
const b = await puppeteer.launch({ executablePath: "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe", headless: "new", args: ["--no-sandbox"] });
const p = await b.newPage();
await p.setViewport({ width: 1440, height: 1000 });
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
await p.goto("http://127.0.0.1:5173/", { waitUntil: "networkidle0" });
await p.evaluate(() => localStorage.setItem("lz:theme", "white"));
await p.reload({ waitUntil: "networkidle0" });
console.log("theme", await p.evaluate(() => document.documentElement.dataset.theme));
console.log("bg", await p.evaluate(() => getComputedStyle(document.body).backgroundColor));
console.log("theme-color", await p.$eval('meta[name="theme-color"]', (n) => n.getAttribute("content")));
await p.screenshot({ path: ".shots/theme-white.png" });
await p.goto("http://127.0.0.1:5173/settings", { waitUntil: "networkidle0" });
console.log("options", await p.$$eval(".theme-switcher:not(.theme-switcher--compact) .theme-option", (n) => n.length));
console.log("overflow", await p.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth));
await p.screenshot({ path: ".shots/theme-white-settings.png", fullPage: true });
console.log("errors", errs);
await b.close();
