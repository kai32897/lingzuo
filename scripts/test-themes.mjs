import puppeteer from "puppeteer-core";
const b = await puppeteer.launch({ executablePath: "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe", headless: "new", args: ["--no-sandbox"] });
const p = await b.newPage();
await p.setViewport({ width: 1440, height: 1000 });
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
p.on("console", (m) => { if (m.type() === "error") errs.push(m.text()); });
await p.goto("http://127.0.0.1:5173/", { waitUntil: "networkidle0" });
console.log("theme initial", await p.evaluate(() => document.documentElement.dataset.theme));
await p.click(".header-style");
await new Promise((r) => setTimeout(r, 400));
console.log("theme after", await p.evaluate(() => document.documentElement.dataset.theme));
console.log("night bg", await p.evaluate(() => getComputedStyle(document.body).backgroundColor));
await p.screenshot({ path: ".shots/theme-night.png", fullPage: false });
await p.click(".header-style");
await new Promise((r) => setTimeout(r, 400));
console.log("theme mint", await p.evaluate(() => document.documentElement.dataset.theme));
await p.screenshot({ path: ".shots/theme-mint.png", fullPage: false });
await p.reload({ waitUntil: "networkidle0" });
console.log("persisted", await p.evaluate(() => document.documentElement.dataset.theme));
await p.goto("http://127.0.0.1:5173/games/bianlidian-yeban", { waitUntil: "networkidle0" });
await new Promise((r) => setTimeout(r, 700));
console.log("lazy detail title", await p.title());
console.log("meta desc", await p.$eval('meta[name="description"]', (n) => n.getAttribute("content")));
console.log("og title", await p.$eval('meta[property="og:title"]', (n) => n.getAttribute("content")));
await p.goto("http://127.0.0.1:5173/settings", { waitUntil: "networkidle0" });
console.log("theme cards", await p.$$eval(".theme-option", (n) => n.length));
console.log("overflow", await p.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth));
console.log("errors", errs);
await b.close();
