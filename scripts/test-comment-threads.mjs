import puppeteer from "puppeteer-core";
const b = await puppeteer.launch({ executablePath: "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe", headless: "new", args: ["--no-sandbox"] });
const p = await b.newPage();
await p.setViewport({ width: 1440, height: 1000 });
p.on("dialog", (dialog) => dialog.accept());
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
await p.goto("http://127.0.0.1:5173/games/bianlidian-yeban", { waitUntil: "networkidle0" });
await new Promise((r) => setTimeout(r, 400));
await p.evaluate(() => document.querySelector("#comments")?.scrollIntoView());
await p.type(".comment-form textarea", "这是一条根评论，用来测试回复串。");
await p.click(".comment-form .btn--primary");
await new Promise((r) => setTimeout(r, 400));
await p.click(".comment .text-btn");
await new Promise((r) => setTimeout(r, 200));
console.log("reply banner", await p.$eval(".comment__reply-banner span", (n) => n.textContent?.trim()));
await p.type(".comment-form textarea", "这是挂在根评论下面的回复。");
await p.click(".comment-form .btn--primary");
await new Promise((r) => setTimeout(r, 400));
console.log("stored", await p.evaluate(() => JSON.parse(localStorage.getItem("lz:comments") || "[]").map((c) => ({ content: c.content, parentId: c.parentId, replyToName: c.replyToName }))));
console.log("dom", await p.evaluate(() => ({ replies: document.querySelectorAll(".comment--reply").length, context: document.querySelector(".comment__reply-to")?.textContent })));
await p.screenshot({ path: ".shots/comment-threads.png" });
await p.click(".comment .comment__delete");
await new Promise((r) => setTimeout(r, 400));
console.log("after delete", await p.evaluate(() => ({ count: JSON.parse(localStorage.getItem("lz:comments") || "[]").length, replies: document.querySelectorAll(".comment--reply").length })));
console.log("errors", errs);
await b.close();
