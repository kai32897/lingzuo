import puppeteer from "puppeteer-core";
const b = await puppeteer.launch({ executablePath: "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe", headless: "new", args: ["--no-sandbox", "--disable-http2", "--host-resolver-rules=MAP lingzuo-ai.netlify.app 13.215.239.219"] });
const p = await b.newPage();
await p.setViewport({ width: 1440, height: 1000 });
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
p.on("console", (m) => { if (m.type() === "error") errs.push(m.text()); });
await p.goto("https://lingzuo-ai.netlify.app/", { waitUntil: "networkidle0", timeout: 60000 });
console.log("home title", await p.title());
console.log("hero", await p.$eval(".hero h1", (n) => n.textContent?.trim()).catch(() => "none"));
await p.goto("https://lingzuo-ai.netlify.app/games/bianlidian-yeban", { waitUntil: "networkidle0", timeout: 60000 });
console.log("detail title", await p.title());
console.log("detail heading", await p.$eval(".work-title", (n) => n.textContent?.trim()).catch(() => "none"));
console.log("og", await p.$eval('meta[property="og:image"]', (n) => n.content));
await p.goto("https://lingzuo-ai.netlify.app/recipes", { waitUntil: "networkidle0", timeout: 60000 });
console.log("recipes", await p.$$eval(".recipe-card", (n) => n.length));
console.log("manifest", await p.$$eval('link[rel="manifest"]', (n) => n.length));
console.log("sw", await p.evaluate(async () => (await navigator.serviceWorker.getRegistrations()).length));
console.log("overflow", await p.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth));
console.log("errors", errs);
await p.screenshot({ path: ".shots/netlify-recipes.png" });
await b.close();
