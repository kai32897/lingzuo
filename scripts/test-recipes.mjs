import puppeteer from "puppeteer-core";
const b = await puppeteer.launch({ executablePath: "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe", headless: "new", args: ["--no-sandbox"] });
const p = await b.newPage();
await p.setViewport({ width: 1440, height: 1000 });
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
await p.goto("http://127.0.0.1:5173/recipes", { waitUntil: "networkidle0" });
const count = () => p.$$eval(".recipe-card", (n) => n.length);
console.log("cards", await count());
await p.type(".recipe-search input", "便利店");
await new Promise((r) => setTimeout(r, 400));
console.log("filtered", await count());
await p.click(".recipe-type-tabs button:nth-child(2)");
await new Promise((r) => setTimeout(r, 300));
console.log("type", await count());
const save = await p.$(".recipe-save");
await save.click();
await new Promise((r) => setTimeout(r, 200));
console.log("saved", await p.evaluate(() => JSON.parse(localStorage.getItem("lz:saved-recipes") || "[]").length));
console.log("overflow", await p.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth));
console.log("manifest", await p.$$eval('link[rel="manifest"]', (n) => n.length));
console.log("errors", errs);
await p.screenshot({ path: ".shots/recipes.png" });
await b.close();
